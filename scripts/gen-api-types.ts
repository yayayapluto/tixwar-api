import { buildOpenApiDocument } from '../src/modules/docs/openapi.ts';

type Schema = Record<string, unknown>;

const SCHEMA_PREFIX = '#/components/schemas/';

const refName = (ref: string): string => ref.slice(SCHEMA_PREFIX.length);

const schemaFromContent = (content: unknown): unknown => {
  if (content === null || typeof content !== 'object') return undefined;
  const entries = Object.values(content as Record<string, { schema?: unknown }>);
  for (const entry of entries) {
    if (entry?.schema !== undefined) return entry.schema;
  }
  return undefined;
};

const literal = (value: unknown): string =>
  typeof value === 'string' ? JSON.stringify(value) : String(value);

const typeOf = (schema: unknown, indent: string): string => {
  if (schema === null || typeof schema !== 'object') return 'unknown';
  const s = schema as Schema;

  if (typeof s.$ref === 'string' && s.$ref.startsWith(SCHEMA_PREFIX)) {
    return `components["schemas"][${JSON.stringify(refName(s.$ref))}]`;
  }

  const nullable = s.nullable === true;
  const type = Array.isArray(s.type)
    ? (s.type as string[])
    : typeof s.type === 'string'
      ? [s.type as string]
      : [];
  const types = type.filter((entry) => entry !== 'null');
  const hasNull = nullable || (Array.isArray(s.type) && (s.type as string[]).includes('null'));

  const base = (): string => {
    if (Array.isArray(s.enum)) return s.enum.map(literal).join(' | ');
    if (Array.isArray(s.anyOf)) {
      return (s.anyOf as unknown[]).map((entry) => typeOf(entry, indent)).join(' | ');
    }
    if (types.includes('array')) {
      const items = typeOf(s.items, `${indent}  `);
      return `Array<${items}>`;
    }
    if (
      types.includes('object') ||
      s.properties !== undefined ||
      s.additionalProperties !== undefined
    ) {
      const props = s.properties as Record<string, unknown> | undefined;
      if (props === undefined) {
        const extra = s.additionalProperties;
        if (
          extra !== null &&
          typeof extra === 'object' &&
          Object.keys(extra as object).length > 0
        ) {
          return `Record<string, ${typeOf(extra, indent)}>`;
        }
        return 'Record<string, unknown>';
      }
      const required = new Set((s.required as string[] | undefined) ?? []);
      const body = Object.entries(props)
        .map(
          ([key, value]) =>
            `${indent}  ${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${typeOf(value, `${indent}  `)};`,
        )
        .join('\n');
      return `{\n${body}\n${indent}}`;
    }
    if (types.includes('integer') || types.includes('number')) return 'number';
    if (types.includes('boolean')) return 'boolean';
    if (types.includes('string')) return 'string';
    return 'unknown';
  };

  const rendered = base();
  return hasNull ? `${rendered} | null` : rendered;
};

const document = buildOpenApiDocument();
const components = (document.components as { schemas: Record<string, Schema> }).schemas;
const paths = document.paths as Record<string, Record<string, Schema>>;

const lines: string[] = [
  '// Generated by `bun run scripts/gen-api-types.ts` from src/modules/docs/openapi.ts.',
  '// Do not edit by hand. Regenerate after changing Zod schemas or routes.',
  '',
  'export interface components {',
  '  schemas: {',
];

for (const [name, schema] of Object.entries(components)) {
  lines.push(`    ${JSON.stringify(name)}: ${typeOf(schema, '    ')};`);
}
lines.push('  };', '}', '');

lines.push('export type Schemas = components["schemas"];', '');

lines.push('export interface paths {');
for (const [path, item] of Object.entries(paths)) {
  lines.push(`  ${JSON.stringify(path)}: {`);
  for (const [method, operation] of Object.entries(item)) {
    if (typeof operation !== 'object' || operation === null) continue;
    const op = operation as Schema;
    lines.push(`    ${method}: {`);
    const body = op.requestBody as Schema | undefined;
    if (body) {
      const schema = schemaFromContent(body.content);
      const optional = body.required === true ? '' : '?';
      lines.push(`      requestBody${optional}: ${typeOf(schema, '      ')};`);
    }
    lines.push('      responses: {');
    const responses = (op.responses as Record<string, Schema> | undefined) ?? {};
    for (const [code, response] of Object.entries(responses)) {
      const schema = schemaFromContent((response as Schema).content);
      lines.push(
        `        ${JSON.stringify(code)}: ${schema ? typeOf(schema, '        ') : 'void'};`,
      );
    }
    lines.push('      };', '    };');
  }
  lines.push('  };');
}
lines.push('}', '');

const jsonPath = 'docs/openapi.json';
const typesPath = 'docs/api-types.d.ts';
await Bun.write(jsonPath, `${JSON.stringify(document, null, 2)}\n`);
await Bun.write(typesPath, lines.join('\n'));

console.log(`wrote ${jsonPath} and ${typesPath}`);
